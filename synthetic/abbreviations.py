def by_expansion() -> dict[str, tuple[str, ...]]:
    """Expansion -> candidate abbreviations, in list order."""
    out: dict[str, list[str]] = {}
    for abbr, expansion in ABBREVIATIONS:
        out.setdefault(expansion, []).append(abbr)
    return {k: tuple(v) for k, v in out.items()}
