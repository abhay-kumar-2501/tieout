"""Fixtures shared across packages: a small generated dataset, and the held-out seed 4."""

from __future__ import annotations

import os
import time
from dataclasses import dataclass
from pathlib import Path

import pytest

from evaluation.evaluate import run_tool
from evaluation.seeds import HELD_OUT_SEED, SeedFiles, ensure_seed
from synthetic.generate import generate, write
from tieout.pipeline import PipelineInputs, run_pipeline
from tieout.results import Results

SMALL_SEED = 7
SMALL_SCALE = 0.15


@pytest.fixture(scope="session")
def small_files(tmp_path_factory: pytest.TempPathFactory) -> dict[str, Path]:
    """A 15% dataset written as the generator writes it: inputs in ``data/seeds/seed_7``
    and truth in ``data/truth/seed_7`` under a temporary root (``root`` in the result)."""
    root = tmp_path_factory.mktemp("small")
    out = root / "data" / "seeds" / f"seed_{SMALL_SEED}"
    truth = root / "data" / "truth" / f"seed_{SMALL_SEED}"
    paths = write(generate(SMALL_SEED, scale=SMALL_SCALE), out, truth)
    return {**paths, "root": root, "truth_dir": truth}


def small_inputs(files: dict[str, Path], **overrides: object) -> PipelineInputs:
    """Pipeline inputs for the small dataset, with the demo's report date."""
    kwargs: dict[str, object] = {
        "acquirer": files["acquirer"],
        "target": files["target"],
        "category_map": files["category_map"],
        "vendor_parents": files["vendor_parents"],
        "as_of": "2026-01-15",
    }
    kwargs.update(overrides)
    return PipelineInputs(**kwargs)  # type: ignore[arg-type]


@pytest.fixture(scope="session")
def small_results(small_files: dict[str, Path]) -> Results:
    """One pipeline run on the small dataset, shared by every test that only reads it."""
    return run_pipeline(small_inputs(small_files))


@pytest.fixture(scope="session")
def timing_slack() -> float:
    """Multiplier for wall-clock bounds; shared CI runners are slower than a laptop."""
    return float(os.environ.get("TIEOUT_TIMING_SLACK", "1"))


@dataclass(frozen=True)
class SeedRun:
    """One full pipeline run on a generated seed, with its wall-clock time."""

    files: SeedFiles
    results: Results
    seconds: float


@pytest.fixture(scope="session")
def seed4(tmp_path_factory: pytest.TempPathFactory) -> SeedRun:
    """The held-out seed (the demo dataset) regenerated and run once per session.

    Inputs and truth are regenerated byte-identically into a temporary directory;
    the run is timed from loading the files to the finished ``Results``.
    """
    root = tmp_path_factory.mktemp("seed4")
    files = ensure_seed(HELD_OUT_SEED, root / "seeds", root / "truth")
    start = time.perf_counter()
    results = run_tool(files)
    return SeedRun(files, results, time.perf_counter() - start)
